/* Stamp canonical, social-share and analytics tags into every page head.
 *
 *   node build/set-meta.js                 (uses https://aqcredix.com)
 *   node build/set-meta.js https://other   (for a staging host)
 *
 * WHY THIS EXISTS — THREE FAULTS IT FIXES.
 *
 * 1. NO CANONICAL ANYWHERE. The site is about to answer on two hostnames at once
 *    (aqcredix.com and the old Vercel host). Without a canonical, a search engine
 *    sees two complete copies of 26 pages and splits the ranking between them — the exact
 *    moment the domain moves is the moment this stops being theoretical.
 *
 * 2. NO OPEN GRAPH ON ANY PAGE. Every WhatsApp forward and LinkedIn post rendered as a
 *    bare grey URL. In this market the link travels by WhatsApp from a quality manager to
 *    a medical director to whoever signs off spending, and a preview that shows nothing
 *    loses that reader before the site is ever opened. The card is assets/og.png — see
 *    build/make-og.js.
 *
 * 3. NO ANALYTICS. Adoption was unobservable. Vercel Web Analytics is used rather than a
 *    third party because the site is already on Vercel: no new vendor, no cost at this
 *    volume, and — because it sets no cookie — no consent banner on a healthcare site
 *    where that question is not worth having. If you outgrow the free tier, swap the one
 *    ANALYTICS line below for Plausible; nothing else changes.
 *
 * IDEMPOTENT. Everything written sits between the two markers below and is replaced
 * wholesale on each run, so this can be re-run after any page is added or retitled and it
 * cannot drift or duplicate. Run it whenever you add a page, exactly like set-version.js.
 *
 * TITLE AND DESCRIPTION ARE NOT INVENTED HERE. They are read from each page's own <title>
 * and <meta name="description">. A share card that disagrees with the page it links to is
 * worse than no card, so there is deliberately no per-page copy stored in this file.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const SITE = (process.argv[2] || "https://aqcredix.com").replace(/\/+$/, "");

const OPEN = "<!-- aq:meta — generated by build/set-meta.js, do not edit by hand -->";
const CLOSE = "<!-- /aq:meta -->";

const ANALYTICS = '<script defer src="/_vercel/insights/script.js"></script>';

/* Directories that are not part of the shipped site: tooling and tests only.
 *
 * DELIBERATELY SHORTER THAN set-version.js's LIST. That one also skips globe, hglobe,
 * kpinet, galaxy2, dna and brain as "abandoned hero experiments". That description is out
 * of date and worth correcting where someone will read it: kpinet drives the KPI mesh on
 * tools/kpi-library.html, globe and hglobe are on the homepage, qglobe is on the
 * dashboard, galaxy2 is on departments, dna is on standards, and face is on the homepage.
 * Seven of the eleven are live. Only galaxy, brain, helix and radar are genuinely
 * unreferenced, and they are kept.
 *
 * It happens not to matter for either script — none of those directories contains a
 * .html file, so nothing is missed — but a stale "these are dead" list is the kind of
 * note that eventually gets acted on. */
const SKIP = new Set([
  "node_modules", ".git", "build", "tests", "tools-build"
]);

/* Pages that must never be indexed, and therefore get no canonical and no share card —
   only the robots directive and analytics.

   summary-review.html is the one that matters. It is deliberately unlinked from every
   public page because it shows the stored NABH wording side by side with our own
   summaries — which is precisely what we are trying to stop publishing. Unlinked is not
   the same as uncrawlable: robots.txt allows everything, so a single stray link would
   have put it in the index. */
const NOINDEX = new Set([
  "tools/summary-review.html",
  "docs/sample-digest-email.html",
  "404.html"
]);

function walk(dir, out = []) {
  for (const name of fs.readdirSync(dir)) {
    if (SKIP.has(name)) continue;
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) walk(full, out);
    else if (name.endsWith(".html")) out.push(full);
  }
  return out;
}

/* "index.html" -> "/", "tools/index.html" -> "/tools/", everything else -> "/that.html".
   Trailing-slash form for directory indexes matters: /tools/ and /tools/index.html are two
   URLs for one page, and the canonical has to name one of them. */
function urlFor(rel) {
  const posix = rel.split(path.sep).join("/");
  if (posix === "index.html") return SITE + "/";
  if (posix.endsWith("/index.html")) return SITE + "/" + posix.slice(0, -"index.html".length);
  return SITE + "/" + posix;
}

/* Attribute values go inside double quotes, so double quotes and angle brackets have to
   go. Ampersands are escaped last or the escaping escapes itself.

   DECODE BEFORE ENCODING. The title and description are read out of the page's own HTML,
   where they are already escaped — a title written "Refund &amp; Cancellation" arrives
   here containing "&amp;", and escaping that again produced "&amp;amp;", which readers
   see verbatim as "&amp;" in the share card and the browser tab. Decoding first makes
   this idempotent: running the script repeatedly can no longer pile up entities. */
function decodeEntities(s) {
  return String(s)
    .replace(/&#(\d+);/g, function (_, d) { return String.fromCodePoint(Number(d)); })
    .replace(/&#x([0-9a-f]+);/gi, function (_, h) { return String.fromCodePoint(parseInt(h, 16)); })
    .replace(/&quot;/g, '"').replace(/&apos;/g, "'")
    .replace(/&lt;/g, "<").replace(/&gt;/g, ">")
    /* &amp; last, so "&amp;lt;" becomes "&lt;" as text rather than a "<" character. */
    .replace(/&amp;/g, "&");
}

function attr(s) {
  return decodeEntities(s)
    .replace(/&/g, "&amp;").replace(/"/g, "&quot;")
    .replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/\s+/g, " ").trim();
}

function firstMatch(html, re) {
  const m = html.match(re);
  return m ? m[1] : "";
}

const SITE_NAME = "AQcredix";
const FALLBACK_DESC =
  "AQcredix teaches healthcare teams to understand NABH accreditation the way an " +
  "assessor does — then runs the calendar, evidence and audits that prove it.";

let changed = 0, skipped = 0;
const files = walk(ROOT);

for (const file of files) {
  const rel = path.relative(ROOT, file);
  const relPosix = rel.split(path.sep).join("/");
  let html = fs.readFileSync(file, "utf8");

  if (!/<\/head>/i.test(html)) { skipped++; continue; }

  /* Strip any previous block before measuring anything, so a re-run reads the page's own
     title rather than one this script wrote earlier. */
  const existing = new RegExp(OPEN.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") +
    "[\\s\\S]*?" + CLOSE.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "\\n?", "g");
  html = html.replace(existing, "");

  const noindex = NOINDEX.has(relPosix) || /name=["']robots["'][^>]*noindex/i.test(html);

  const lines = [OPEN];

  if (noindex) {
    /* Pages already carrying their own robots tag keep it; the rest get one here. */
    if (!/name=["']robots["']/i.test(html)) {
      lines.push('<meta name="robots" content="noindex, nofollow">');
    }
  } else {
    const title = firstMatch(html, /<title>([\s\S]*?)<\/title>/i) || SITE_NAME;
    const desc = firstMatch(html, /<meta\s+name=["']description["']\s+content=["']([\s\S]*?)["']\s*\/?>/i)
                 || FALLBACK_DESC;
    const url = urlFor(rel);

    lines.push(
      '<link rel="canonical" href="' + url + '">',
      '<meta property="og:type" content="website">',
      '<meta property="og:site_name" content="' + SITE_NAME + '">',
      '<meta property="og:locale" content="en_IN">',
      '<meta property="og:url" content="' + url + '">',
      '<meta property="og:title" content="' + attr(title) + '">',
      '<meta property="og:description" content="' + attr(desc) + '">',
      '<meta property="og:image" content="' + SITE + '/assets/og.png">',
      /* secure_url and type are older Open Graph properties that most crawlers no longer
         need — but WhatsApp is the one that matters here and it has historically been the
         fussiest reader in the family. They cost two lines and remove a whole class of
         "why is there no preview" from the list of things to investigate. */
      '<meta property="og:image:secure_url" content="' + SITE + '/assets/og.png">',
      '<meta property="og:image:type" content="image/png">',
      '<meta property="og:image:width" content="1200">',
      '<meta property="og:image:height" content="630">',
      '<meta property="og:image:alt" content="AQcredix — know it before the assessor does">',
      '<meta name="twitter:card" content="summary_large_image">',
      '<meta name="twitter:title" content="' + attr(title) + '">',
      '<meta name="twitter:description" content="' + attr(desc) + '">',
      '<meta name="twitter:image" content="' + SITE + '/assets/og.png">'
    );
  }

  lines.push(ANALYTICS, CLOSE);

  html = html.replace(/<\/head>/i, lines.join("\n") + "\n</head>");
  fs.writeFileSync(file, html);
  changed++;
}

console.log("set-meta: stamped " + changed + " pages at " + SITE +
            (skipped ? " (" + skipped + " skipped, no <head>)" : ""));
