/* Generate the dotted world map used on the contact page.
 *
 * WHY THIS IS A BUILD STEP AND NOT RUNTIME WORK.
 * The dots come from hglobe/world-borders.js — the same country polygons the globe already
 * uses, so the map and the globe agree about where land is. Testing a grid of ~12,000
 * points against 82KB of polygons is fine once, on a laptop; doing it in the browser on
 * every page load is not. So it runs here and ships a bitmask.
 *
 * WHY A BITMASK RATHER THAN A LIST OF COORDINATES.
 * The grid is regular, so the only information that varies is "land or not" per cell. As
 * coordinate pairs that is ~25KB of JSON; as one bit per cell it is under 2KB, and the
 * decode is a dozen lines. The grid dimensions are shipped with it so the client never has
 * to guess.
 *
 *   node build/gen-worldmap-dots.js
 */
const fs = require("fs");
const path = require("path");
const ROOT = path.join(__dirname, "..");

/* The band worth drawing. Below -58 there is only Antarctica, which on an equirectangular
   projection smears across the entire bottom edge and reads as a bar rather than a
   continent; above 78 there is nothing but ice. Cutting both makes the map look like the
   world people picture. */
const LAT_MIN = -58, LAT_MAX = 78;
const LON_MIN = -180, LON_MAX = 180;
const STEP = 2;                       /* degrees between dots */

const COLS = Math.round((LON_MAX - LON_MIN) / STEP);
const ROWS = Math.round((LAT_MAX - LAT_MIN) / STEP);

global.window = {};
require(path.join(ROOT, "hglobe", "world-borders.js"));
const POLYS = global.window.WORLD_BORDERS;
if (!Array.isArray(POLYS) || !POLYS.length) {
  console.error("world-borders.js did not provide WORLD_BORDERS");
  process.exit(1);
}

/* Bounding box per polygon. Without this every dot is tested against every ring and the
   run takes minutes instead of a second. */
const boxes = POLYS.map(flat => {
  let minX = 180, maxX = -180, minY = 90, maxY = -90;
  for (let i = 0; i < flat.length; i += 2) {
    if (flat[i] < minX) minX = flat[i];
    if (flat[i] > maxX) maxX = flat[i];
    if (flat[i + 1] < minY) minY = flat[i + 1];
    if (flat[i + 1] > maxY) maxY = flat[i + 1];
  }
  return { minX, maxX, minY, maxY };
});

/* Ray casting. The rings are closed, so the last vertex joins the first. */
function inside(flat, x, y) {
  let hit = false;
  const n = flat.length / 2;
  for (let i = 0, j = n - 1; i < n; j = i++) {
    const xi = flat[i * 2], yi = flat[i * 2 + 1];
    const xj = flat[j * 2], yj = flat[j * 2 + 1];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

const bits = new Uint8Array(Math.ceil((COLS * ROWS) / 8));
let land = 0;
for (let r = 0; r < ROWS; r++) {
  /* Sample the middle of each cell rather than its corner, so a coastline does not
     systematically lose or gain a row. */
  const lat = LAT_MAX - (r + 0.5) * STEP;
  for (let c = 0; c < COLS; c++) {
    const lon = LON_MIN + (c + 0.5) * STEP;
    let on = false;
    for (let p = 0; p < POLYS.length; p++) {
      const b = boxes[p];
      if (lon < b.minX || lon > b.maxX || lat < b.minY || lat > b.maxY) continue;
      if (inside(POLYS[p], lon, lat)) { on = true; break; }
    }
    if (on) { const i = r * COLS + c; bits[i >> 3] |= 1 << (i & 7); land++; }
  }
}

const b64 = Buffer.from(bits).toString("base64");
const out = `/* GENERATED by build/gen-worldmap-dots.js — do not edit by hand.
 *
 * One bit per grid cell, row-major from the top-left of the drawn band: 1 means land.
 * Built from hglobe/world-borders.js, so this map and the 3D globes agree about where the
 * coastlines are. Re-run the generator if those borders ever change.
 *
 * ${land} land cells in a ${COLS}x${ROWS} grid, ${STEP} degrees apart,
 * covering longitude ${LON_MIN}..${LON_MAX} and latitude ${LAT_MIN}..${LAT_MAX}.
 */
window.AQ_WORLD_DOTS = {
  cols: ${COLS}, rows: ${ROWS}, step: ${STEP},
  lonMin: ${LON_MIN}, lonMax: ${LON_MAX}, latMin: ${LAT_MIN}, latMax: ${LAT_MAX},
  bits: "${b64}"
};
`;
const dest = path.join(ROOT, "contact", "worldmap-dots.js");
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);

console.log("grid       : " + COLS + " x " + ROWS + " (" + STEP + " degrees)");
console.log("land cells : " + land + " of " + COLS * ROWS +
  "  (" + ((land / (COLS * ROWS)) * 100).toFixed(1) + "%)");
console.log("payload    : " + (b64.length / 1024).toFixed(1) + " KB base64");
console.log("written    : contact/worldmap-dots.js");
