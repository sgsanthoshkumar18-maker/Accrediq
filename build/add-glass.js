/* Put the glass layer on every page.
 *
 * Two stylesheets and a four-line enabler, inserted before </head>. Run it
 * again after adding a page and it will pick that page up; run it twice on the
 * same page and nothing happens, because it checks for its own marker first.
 *
 * WHY AN ENABLER RATHER THAN JUST THE STYLESHEETS. Everything in
 * aq-glass-apply.css is scoped to :root[data-glass]. With the attribute absent
 * the site renders exactly as it did before, so the whole treatment has an off
 * switch: ?glass=0 on any URL turns it off and remembers that, ?glass=1 turns
 * it back on. On a product hospitals depend on, a visual change this broad
 * should be reversible by the person looking at it, not only by a deploy.
 *
 * The prefix is computed from how deep the file sits, because the stylesheets
 * live at the repo root and workspace/audit.html has to reach them with ../.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const MARK = "aq:glass";

/* Folders that are not the site: build output, dependencies, scratch previews. */
const SKIP_DIR = new Set(["node_modules", ".git", ".vercel", "build", "tests"]);

function walk(dir, out) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (SKIP_DIR.has(entry.name)) continue;
      walk(path.join(dir, entry.name), out);
    } else if (entry.isFile() && entry.name.endsWith(".html")) {
      out.push(path.join(dir, entry.name));
    }
  }
  return out;
}

const files = walk(ROOT, []).filter(f => {
  const rel = path.relative(ROOT, f).replace(/\\/g, "/");
  /* Underscore-prefixed files are local previews and scratch pages, never
     shipped, and the blank-checklist print sheet must stay plain paper. */
  if (rel.split("/").some(seg => seg.startsWith("_"))) return false;
  if (rel === "audit/blank-checklist.html") return false;
  return true;
});

let added = 0, already = 0, skipped = 0;

for (const file of files) {
  let html = fs.readFileSync(file, "utf8");

  if (html.indexOf(MARK) > -1) { already++; continue; }
  if (html.indexOf("</head>") < 0) { skipped++; continue; }

  const rel = path.relative(ROOT, file).replace(/\\/g, "/");
  const depth = rel.split("/").length - 1;
  const base = depth === 0 ? "" : "../".repeat(depth);

  const block =
    `<!-- ${MARK} — generated by build/add-glass.js, do not edit by hand -->\n` +
    `<link rel="stylesheet" href="${base}aq-glass.css?v=20260101a">\n` +
    `<link rel="stylesheet" href="${base}aq-glass-apply.css?v=20260101a">\n` +
    `<script>(function(){try{var p=new URLSearchParams(location.search);` +
    `if(p.get("glass")==="0"){localStorage.setItem("aq-glass","off");}` +
    `else if(p.get("glass")==="1"){localStorage.removeItem("aq-glass");}` +
    `if(localStorage.getItem("aq-glass")!=="off"){` +
    `document.documentElement.setAttribute("data-glass","");}}catch(e){` +
    `document.documentElement.setAttribute("data-glass","");}})();</script>\n` +
    `<!-- /${MARK} -->\n`;

  html = html.replace("</head>", block + "</head>");
  fs.writeFileSync(file, html);
  added++;
}

console.log(
  "glass layer: " + added + " pages updated, " + already + " already had it, " +
  skipped + " skipped (no </head>)"
);
